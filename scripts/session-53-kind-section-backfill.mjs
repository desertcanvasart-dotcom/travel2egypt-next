const client = createClient({
  projectId: 'ufallvd2',
  dataset: 'migration-staging',
  apiVersion: '2024-12-01',
  token,
  useCdn: false,
});

async function main() {
  const current = await client.fetch(
    '*[_type=="guideArticle"]{_id, kind, section}'
  );
  const cur = new Map(current.map((d) => [d._id, d]));

  let kindPatched = 0, kindSkipped = 0, sectionPatched = 0, sectionSkipped = 0;
  const failures = [];
  let i = 0;

  for (const item of PLAN) {
    i++;
    const doc = cur.get(item.id);
    if (!doc) { failures.push({ id: item.id, reason: 'doc not found' }); continue; }

    const set = {};
    if (!doc.kind) set.kind = item.kind;
    else kindSkipped++;

    if (!doc.section) set.section = SECTION_MAP[item.kind];
    else sectionSkipped++;

    if (Object.keys(set).length === 0) {
      if (i % 50 === 0) console.log(`  ...${i}/${PLAN.length}`);
      continue;
    }
    try {
      await client.patch(item.id).set(set).commit();
      if (set.kind) kindPatched++;
      if (set.section) sectionPatched++;
    } catch (e) {
      failures.push({ id: item.id, reason: String(e).slice(0, 120) });
    }
    if (i % 50 === 0) console.log(`  ...${i}/${PLAN.length}`);
  }

  console.log('');
  console.log('=== Backfill complete ===');
  console.log('kind:    patched', kindPatched, '| skipped (already set)', kindSkipped);
  console.log('section: patched', sectionPatched, '| skipped (already set)', sectionSkipped);
  console.log('failures:', failures.length);
  for (const f of failures) console.log('  FAIL', f.id, '-', f.reason);
}

main().catch((e) => { console.error(e); process.exit(1); });
